function dagsDir(): string {
  if (process.env.ETL_AIRFLOW_DAGS_DIR) {
    return process.env.ETL_AIRFLOW_DAGS_DIR;
  }
  if (process.env.AIRFLOW_HOME) {
    return path.join(process.env.AIRFLOW_HOME, 'dags');
  }
  return '';
}

function safeDagFileBase(name: string, versionId: number): string {
  const safe = name.replace(/[^a-zA-Z0-9_]+/g, '_').replace(/^_|_$/g, '') || 'task';
  return `etl_${safe}_${versionId}`;
}

/** 旧版 DAG 文件名 `etl_{name}_{versionId}.py`（发布新版本时顺带清理） */
function deleteLegacySlugDagFile(name: string, versionId: number): void {
  const dir = dagsDir();
  if (!dir) return;
  const fp = path.join(dir, `${safeDagFileBase(name, versionId)}.py`);
  try {
    fs.unlinkSync(fp);
  } catch {
    /* ignore */
  }
}

/** 当前版 DAG 文件名 `auto_generate_{etl_task_info.id}.py` */
function deleteAutoGenerateDagFile(etlTaskInfoId: number): void {
  const dir = dagsDir();
  if (!dir) return;
  const fp = path.join(dir, `auto_generate_${etlTaskInfoId}.py`);
  try {
    fs.unlinkSync(fp);
  } catch {
    /* ignore */
  }
}

