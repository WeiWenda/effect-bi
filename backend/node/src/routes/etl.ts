router.delete('/tasks/versions/:id', async (req: Request, res: Response): Promise<void> => {
  try {
    const id = parseInt(String(req.params.id), 10);
    if (Number.isNaN(id)) {
      res.status(400).json({ error: 'Invalid id' });
      return;
    }
    const check = await pool.query(
      `SELECT i.name, v.is_published, i.id AS etl_task_id FROM etl_task_versions v
       JOIN etl_task_info i ON i.id = v.etl_task_id WHERE v.id = $1`,
      [id]
    );
    if (check.rows.length === 0) {
      res.status(404).json({ error: 'Version not found' });
      return;
    }

    const refCounts = await pool.query(
      `SELECT
         (SELECT COUNT(*)::int FROM etl_table_partition_detail WHERE etl_task_version_id = $1) AS n_partition,
         (SELECT COUNT(*)::int FROM etl_task_run_instances WHERE etl_task_version_id = $1) AS n_run`,
      [id]
    );
    const nPartition = refCounts.rows[0]?.n_partition as number;
    const nRun = refCounts.rows[0]?.n_run as number;
    if ((nPartition ?? 0) > 0 || (nRun ?? 0) > 0) {
      const parts: string[] = [];
      if ((nPartition ?? 0) > 0) {
        parts.push(`产出分区登记（etl_table_partition_detail）${nPartition} 条`);
      }
      if ((nRun ?? 0) > 0) {
        parts.push(`运行实例（etl_task_run_instances）${nRun} 条`);
      }
      res.status(409).json({
        error: `该版本仍被引用，无法删除：${parts.join('；')}。`,
        refs: { partitionDetails: nPartition ?? 0, runInstances: nRun ?? 0 },
      });
      return;
    }

    if (check.rows[0].is_published) {
      const name = check.rows[0].name as string;
      deleteLegacySlugDagFile(name, id);
      deleteAutoGenerateDagFile(check.rows[0].etl_task_id as number);
    }
    await pool.query('DELETE FROM etl_task_versions WHERE id = $1', [id]);
    res.json({ success: true });
  } catch (error) {
    console.error('Error deleting task version:', error);
    res.status(500).json({ error: 'Failed to delete' });
  }
});

