/** Delete logical task: all versions (deployments cascade), folder placement, and published DAG files. */
router.delete('/tasks', async (req: Request, res: Response): Promise<void> => {
  try {
    const name = typeof req.query.name === 'string' ? req.query.name.trim() : '';
    if (!name) {
      res.status(400).json({ error: 'name query is required' });
      return;
    }

    const versions = await pool.query(
      `SELECT v.id, v.is_published, i.id AS etl_task_id FROM etl_task_versions v
       JOIN etl_task_info i ON i.id = v.etl_task_id WHERE i.name = $1`,
      [name]
    );
    if (versions.rows.length === 0) {
      res.status(404).json({ error: 'Task not found' });
      return;
    }

    const taskInfoId = versions.rows[0].etl_task_id as number;
    let removeAutoGenerate = false;
    for (const row of versions.rows) {
      if (row.is_published) {
        removeAutoGenerate = true;
        deleteLegacySlugDagFile(name, row.id as number);
      }
    }
    if (removeAutoGenerate) {
      deleteAutoGenerateDagFile(taskInfoId);
    }

    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      await client.query('DELETE FROM etl_task_info WHERE name = $1', [name]);
      await client.query('COMMIT');
    } catch (err) {
      await client.query('ROLLBACK');
      throw err;
    } finally {
      client.release();
    }

    res.json({ success: true });
  } catch (error) {
    console.error('Error deleting etl task:', error);
    res.status(500).json({ error: 'Failed to delete task' });
  }
});

