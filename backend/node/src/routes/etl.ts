/** 按三层元数据查询 etl_table_partition_detail（血缘表详情「产出信息」）；分区日期倒序 + 分页 */
router.get('/table-partition-details', async (req: Request, res: Response): Promise<void> => {
  try {
    const catalog = typeof req.query.catalog === 'string' ? req.query.catalog.trim() : '';
    const database = typeof req.query.database === 'string' ? req.query.database.trim() : '';
    const table = typeof req.query.table === 'string' ? req.query.table.trim() : '';
    if (!catalog || !database || !table) {
      res.status(400).json({ error: 'catalog, database, and table query parameters are required' });
      return;
    }
    const pageRaw = parseInt(String(req.query.page ?? '1'), 10);
    const pageSizeRaw = parseInt(String(req.query.pageSize ?? '20'), 10);
    const page = Math.max(1, Number.isNaN(pageRaw) ? 1 : pageRaw);
    const pageSize = Math.min(100, Math.max(1, Number.isNaN(pageSizeRaw) ? 20 : pageSizeRaw));
    const offset = (page - 1) * pageSize;

    const countResult = await pool.query(
      `SELECT COUNT(*)::int AS c FROM etl_table_partition_detail
       WHERE catalog_name = $1 AND database_name = $2 AND table_name = $3`,
      [catalog, database, table]
    );
    const total = (countResult.rows[0]?.c as number) ?? 0;

    const result = await pool.query(
      `SELECT id, catalog_name, database_name, table_name,
              primary_partition_key, secondary_partition_key, etl_task_version_id,
              partition_date, is_verified, running_status, last_success_at,
              created_at, updated_at
       FROM etl_table_partition_detail
       WHERE catalog_name = $1 AND database_name = $2 AND table_name = $3
       ORDER BY partition_date DESC NULLS LAST, primary_partition_key ASC, secondary_partition_key ASC
       LIMIT $4 OFFSET $5`,
      [catalog, database, table, pageSize, offset]
    );
    const partitionDetails = result.rows.map(row => ({
      id: row.id as number,
      catalogName: row.catalog_name as string,
      databaseName: row.database_name as string,
      tableName: row.table_name as string,
      primaryPartitionKey: row.primary_partition_key as string,
      secondaryPartitionKey: row.secondary_partition_key as string,
      etlTaskVersionId: row.etl_task_version_id as number | null,
      partitionDate: row.partition_date,
      isVerified: row.is_verified as boolean,
      runningStatus: row.running_status as string,
      lastSuccessAt: row.last_success_at,
      createdAt: row.created_at,
      updatedAt: row.updated_at,
    }));
    res.json({ partitionDetails, total, page, pageSize });
  } catch (error) {
    console.error('Error listing table partition details:', error);
    res.status(500).json({ error: 'Failed to list partition details' });
  }
});

